// Builds functions/_lib/staff.js (the server's staff directory) from site/ants.js, so both sides agree on who exists.
// Run by deploy.sh. One entry per person; cluster-wide staff carry every site they serve.
import fs from "node:fs"; import vm from "node:vm";
const ctx = { console, Date, Math, JSON, localStorage: { getItem: () => null, setItem() {} } }; ctx.globalThis = ctx;
vm.runInNewContext(fs.readFileSync(new URL("../site/ants.js", import.meta.url), "utf8"), ctx);
const A = ctx.ANTS, byUid = {};
for (const p of A.staff()) {
  const s = byUid[p.uid] || (byUid[p.uid] = { uid: p.uid, name: p.name, role: p.role, antsRole: p.antsRole, cluster: p.cluster, site: p.site, zone: p.zone, sites: [] });
  if (p.site && !s.sites.includes(p.site)) s.sites.push(p.site);
}
const clusters = A.clusters().map(c => ({ code: c.code, sites: c.sites.map(s => s.code) }));
const agencies = A.agencies().map(a => ({ id: a.id, clusters: a.clusters }));
const out = `// GENERATED by tools/build-staff.mjs from site/ants.js. Do not edit.\nexport const STAFF = ${JSON.stringify(Object.values(byUid))};\nexport const CLUSTERS = ${JSON.stringify(clusters)};\nexport const AGENCIES = ${JSON.stringify(agencies)};\n`;
fs.writeFileSync(new URL("../functions/_lib/staff.js", import.meta.url), out);
console.log(`staff: ${Object.keys(byUid).length} people (${Object.values(byUid).filter(p => p.role !== "agency").length} staff + ${agencies.length} agencies), ${clusters.reduce((n, c) => n + c.sites.length, 0)} sites`);
